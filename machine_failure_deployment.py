import streamlit as st
import pandas as pd
import joblib

model = joblib.load("Machine_Failure_Prediction.pkl")

st.title("Machine_Failure_Prediction.pkl")

tempMode = st.number_input("tempMode"),
AQ = st.numder_input("AQ"),
USS = st.number_input("USS"),
CS = st.number_input("CS"),
VOC = st.number_input("VOC"),
RP = st.number_input("RP"),
IP = st.number_input("IP"),
Temperature = st.number_input("Temperature "),
fail = st.number_input("fail")

df = pd.DataFrame({
    "tempMode": tempMode,
    "AQ": AQ,
    "USS": USS,
    "CS": CS,
    "VOC": VOC,
    "RP": RP,
    "IP": IP,
    "Temperature": Temperature,
    "fail": fail
})

if st.button("Predict"):
    prediction = model.predict(df)[0]

    if prediction == 0:
      st.write("Machine Deployed Successfully")
    else:
        st.write("Machine Failed")
